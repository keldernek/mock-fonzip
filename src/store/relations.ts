export interface Relation {
  readonly from: keyof Records;
  readonly field: string;
  readonly to: keyof Records;
}

function relation<F extends keyof Records>(
  from: F,
  field: Exclude<keyof Records[F], "id"> & string,
  to: keyof Records,
): Relation {
  return { from, field, to };
}

