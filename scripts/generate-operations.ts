import {
  deref,
  isJsonObject,
  type Json,
  type JsonObject,
} from "../src/spec/json";
import { isMethod, type HttpMethod } from "../src/spec/routes";

interface SpecOperation {
  readonly operationId: string;
  readonly method: HttpMethod;
  readonly path: string;
  readonly parameterLocations: ReadonlySet<string>;
  readonly jsonBody: boolean;
  readonly jsonSuccess: boolean;
}

interface Alias {
  readonly suffix: string;
  readonly has: (operation: SpecOperation) => boolean;
  readonly type: (operation: string) => string;
}

const ALIASES: readonly Alias[] = [
  {
    suffix: "Response",
    has: (operation) => operation.jsonSuccess,
    type: (operation) => `SuccessResponseJSON<${operation}>`,
  },
  {
    suffix: "Body",
    has: (operation) => operation.jsonBody,
    // RequestBodyJSON indexes `requestBody` as declared, and an optional
    // body's `X | undefined` has no keys, so it would resolve to never.
    type: (operation) => `RequestBodyJSON<Required<${operation}>>`,
  },
  {
    suffix: "Query",
    has: (operation) => operation.parameterLocations.has("query"),
    type: (operation) => `NonNullable<${operation}["parameters"]["query"]>`,
  },
  {
    suffix: "Path",
    has: (operation) => operation.parameterLocations.has("path"),
    type: (operation) => `${operation}["parameters"]["path"]`,
  },
];

function hasJsonContent(spec: JsonObject, node: Json | undefined): boolean {
  const resolved = deref(spec, node);
  return (
    isJsonObject(resolved) &&
    isJsonObject(resolved.content) &&
    Object.keys(resolved.content).some((media) => media.endsWith("/json"))
  );
}

function readOperations(spec: JsonObject): SpecOperation[] {
  if (!isJsonObject(spec.paths)) throw new Error("the spec has no paths");
  return Object.entries(spec.paths).flatMap(([path, item]) => {
    if (!isJsonObject(item)) return [];
    const shared = Array.isArray(item.parameters) ? item.parameters : [];
    return Object.entries(item).flatMap(([method, operation]) => {
      if (!isMethod(method) || !isJsonObject(operation)) return [];
      const { operationId, parameters, requestBody, responses } = operation;
      if (typeof operationId !== "string") {
        throw new Error(`${method} ${path} has no operationId`);
      }
      const own = Array.isArray(parameters) ? parameters : [];
      return [
        {
          operationId,
          method,
          path,
          parameterLocations: new Set(
            [...shared, ...own].flatMap((parameter) => {
              const resolved = deref(spec, parameter);
              return isJsonObject(resolved) && typeof resolved.in === "string"
                ? [resolved.in]
                : [];
            }),
          ),
          jsonBody: hasJsonContent(spec, requestBody),
          jsonSuccess:
            isJsonObject(responses) && hasJsonContent(spec, responses["200"]),
        },
      ];
    });
  });
}

function pascalCase(operationId: string): string {
  return operationId
    .split(/[^A-Za-z0-9]+/)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join("");
}

export function generateOperations(spec: JsonObject): string {
  const operations = readOperations(spec);
  const table = operations.map(
    ({ operationId, method, path }) =>
      `  ${operationId}: { method: "${method.toUpperCase()}", path: "${path}" },`,
  );
  const blocks = operations.map((operation) => {
    const name = pascalCase(operation.operationId);
    const source = `operations["${operation.operationId}"]`;
    const route = `\`${operation.method.toUpperCase()} ${operation.path}\` (${operation.operationId})`;
    return ALIASES.filter((alias) => alias.has(operation))
      .map(
        (alias) =>
          `/** ${route} */\nexport type ${name}${alias.suffix} = ${alias.type(source)};`,
      )
      .join("\n");
  });
  return [
    "/**",
    " * Generated by `bun run generate` from spec/fonzip-openapi.yaml.",
    " * Do not make direct changes to the file.",
    " */",
    "",
    'import type { HttpMethod, RequestBodyJSON, SuccessResponseJSON } from "openapi-typescript-helpers";',
    "",
    'import type { operations, paths } from "./api.js";',
    "",
    "export const OPERATIONS = {",
    ...table,
    "} as const satisfies {",
    "  readonly [K in keyof operations]: {",
    "    readonly method: Uppercase<HttpMethod>;",
    "    readonly path: keyof paths;",
    "  };",
    "};",
    "",
    blocks.filter((block) => block !== "").join("\n\n"),
    "",
  ].join("\n");
}
